const messages: Record<Lang, Record<MessageKey, string>> = {
  en,
  "zh-TW": zhTW,
  "zh-CN": zhCN,
  ja,
};

let current: Lang = "zh-TW";

export function getLanguage(): Lang {
  return current;
}

export function isLang(value: string): value is Lang {
  return (LANGS as readonly string[]).includes(value);
}

export function normalizeLanguage(value: string): Lang {
  return isLang(value) ? value : "zh-TW";
}

export function setLanguage(lang: string): boolean {
  const next = normalizeLanguage(lang);
  const changed = next !== current;
  current = next;
  document.documentElement.lang = next;
  return changed;
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const template = messages[current][key] ?? messages.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = vars[name];
    return value === undefined ? whole : String(value);
  });
}

export function applyStatic(root: ParentNode = document): void {
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
    const key = el.dataset.i18n as MessageKey | undefined;
    if (key) el.textContent = t(key);
  }
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n-aria]")) {
    const key = el.getAttribute("data-i18n-aria") as MessageKey | null;
    if (key) el.setAttribute("aria-label", t(key));
  }
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
    const key = el.getAttribute("data-i18n-title") as MessageKey | null;
    if (key) el.title = t(key);
  }
}

